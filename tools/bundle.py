#!/usr/bin/env python3
"""Joins hooks/src/*.tsx into hooks/register.tsx, the one module the engine loads.

Why: the engine follows `$` only into functions declared in the same file as
the hook that passes it, never across an import, so every function that takes
`$` has to end up in one file. The sources stay split by feature; this script
is the join. Pure modules with no `$` (hooks/outline.ts) stay real imports.

Rules for a source file:
- import from 'claude-code', '../../types', '../<pure module>' or './<source>';
- top-level names must be unique across all sources (the bundle is one scope);
- `export` is fine and is dropped in the bundle, except main's `register`.

Usage: python3 tools/bundle.py   (from anywhere)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'hooks' / 'src'
OUT = ROOT / 'hooks' / 'register.tsx'
ORDER = ['core', 'tracking', 'transcript', 'stats', 'search', 'export', 'pane', 'main']

IMPORT = re.compile(r"^import\s+(type\s+)?(\{[^}]*\}|[\w*\s]+)\s+from\s+'([^']+)'\s*\n", re.M | re.S)
DECL = re.compile(r'^(?:export\s+)?(?:async\s+function|function|const|let|type|class)\s+([A-Za-z_$][\w$]*)', re.M)


def main() -> int:
    present = {p.stem for p in SRC.glob('*.tsx')}
    unknown = present - set(ORDER)
    if unknown:
        print(f'bundle: add {sorted(unknown)} to ORDER in tools/bundle.py', file=sys.stderr)
        return 1

    values: dict[str, set[str]] = {}
    types: dict[str, set[str]] = {}
    bodies: list[str] = []
    owner: dict[str, str] = {}

    for name in ORDER:
        path = SRC / f'{name}.tsx'
        if not path.exists():
            continue
        text = path.read_text()
        for match in IMPORT.finditer(text):
            is_type, names, source = match.group(1), match.group(2), match.group(3)
            if source.startswith('./'):
                continue
            source = source.replace('../../types', '../types')
            if source.startswith('../') and not source.startswith('../types'):
                source = './' + source[3:]
            listed = {n.strip() for n in names.strip('{} \n').split(',') if n.strip()}
            (types if is_type else values).setdefault(source, set()).update(listed)
        body = IMPORT.sub('', text).strip('\n')
        for decl in DECL.finditer(body):
            top = decl.group(0)
            if body[decl.start() - 1:decl.start()] not in ('', '\n'):
                continue
            if decl.group(1) in owner and not top.startswith(' '):
                print(f'bundle: {decl.group(1)} is declared in both {owner[decl.group(1)]} and {name}', file=sys.stderr)
                return 1
            owner[decl.group(1)] = name
        if name != 'main':
            body = re.sub(r'^export\s+', '', body, flags=re.M)
        bodies.append(f'// ---- hooks/src/{name}.tsx\n\n{body}')

    lines = ['// Generated by tools/bundle.py from hooks/src/*.tsx. Edit those, then run it.', '']
    for source in sorted(set(values) | set(types), key=lambda s: (s != 'claude-code', s)):
        if source in values:
            names = sorted(values[source] - types.get(source, set()), key=str.lower)
            lines.append(f"import {{ {', '.join(names)} }} from '{source}'")
        if source in types:
            names = sorted(types[source] - values.get(source, set()), key=str.lower)
            if names:
                lines.append(f"import type {{ {', '.join(names)} }} from '{source}'")
    OUT.write_text('\n'.join(lines) + '\n\n' + '\n\n'.join(bodies) + '\n')
    print(f'bundle: wrote {OUT.relative_to(ROOT)} from {len(bodies)} sources')

    return 0


if __name__ == '__main__':
    sys.exit(main())
